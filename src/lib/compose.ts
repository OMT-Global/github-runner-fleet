import YAML from "yaml";
import type { DeploymentEnv } from "./env.js";
import type { PoolConfig, ResolvedConfig } from "./config.js";
import { buildCommonRunnerEnv } from "./runner-plane.js";
import { renderTelemetryEnvironment } from "./config.js";

export function renderCompose(
  config: ResolvedConfig,
  env: DeploymentEnv
): string {
  const services = Object.fromEntries(
    config.pools.flatMap((pool) =>
      Array.from({ length: pool.size }, (_, index) => {
        const serviceName = buildServiceName(pool, index);
        return [serviceName, renderService(pool, index)];
      })
    )
  );

  const document = new YAML.Document({
    name: env.composeProjectName,
    services
  });

  return [
    "# Generated by pnpm render-compose --output docker-compose.generated.yml",
    "# Shell-only runners: no Docker socket, no privileged mode, no published ports.",
    document.toString().trimEnd()
  ].join("\n");
}

export function buildServiceName(pool: PoolConfig, index: number): string {
  return `${pool.key}-runner-${formatIndex(index)}`;
}

export function buildRunnerName(pool: PoolConfig, index: number): string {
  return buildServiceName(pool, index);
}

export function buildRunnerStateDir(pool: PoolConfig, index: number): string {
  return `${pool.runnerRoot}/runner-${formatIndex(index)}`;
}

function renderService(pool: PoolConfig, index: number): Record<string, unknown> {
  const runnerStateDir = buildRunnerStateDir(pool, index);
  const environment: Record<string, string> = {
    ...buildCommonRunnerEnv({
      organization: pool.organization,
      runnerName: buildRunnerName(pool, index),
      runnerGroup: pool.runnerGroup,
      poolKey: pool.key,
      plane: "synology",
      labels: pool.labels,
      visibility: pool.visibility,
      repositoryAccess: pool.repositoryAccess,
      runnerStateDir,
      runnerLogDir: `${runnerStateDir}/logs`,
      runnerWorkDir: "/tmp/github-runner-work",
      runnerTemp: "/tmp/github-runner-temp",
      runnerToolCache: "/opt/hostedtoolcache"
    }),
    AUDIT_LOG_FILE: `${runnerStateDir}/audit.jsonl`,
    ...renderTelemetryEnvironment(pool.telemetry, {
      serviceName: "github-runner-fleet.synology",
      resourceAttributes: {
        "deployment.environment": pool.visibility,
        "github.organization": pool.organization,
        "runner.group": pool.runnerGroup,
        "runner.name": buildRunnerName(pool, index),
        "runner.pool": pool.key,
        "runner.plane": "synology"
      }
    })
  };

  if (pool.repositoryAccess === "selected") {
    environment.RUNNER_ALLOWED_REPOSITORIES = pool.allowedRepositories.join(",");
  }

  const service: Record<string, unknown> = {
    image: pool.imageRef,
    container_name: buildServiceName(pool, index),
    hostname: buildRunnerName(pool, index),
    restart: "unless-stopped",
    stop_grace_period: "2m",
    environment,
    volumes: [`${runnerStateDir}:${runnerStateDir}`],
    security_opt: ["no-new-privileges:true"],
    cap_drop: ["ALL"],
    labels: {
      "com.synology-gh-runner.pool": pool.key,
      "com.synology-gh-runner.visibility": pool.visibility,
      "com.synology-gh-runner.repository-access": pool.repositoryAccess,
      "com.synology-gh-runner.allowed-repositories":
        pool.repositoryAccess === "all"
          ? "all"
          : pool.allowedRepositories.join(","),
      "com.synology-gh-runner.shell-only": "true"
    }
  };

  if (pool.architecture !== "auto") {
    service.platform = `linux/${pool.architecture}`;
  }

  if (pool.resources.cpus) {
    service.cpus = pool.resources.cpus;
  }

  if (pool.resources.pidsLimit !== undefined) {
    service.pids_limit = pool.resources.pidsLimit;
  }

  if (pool.resources.memory) {
    service.mem_limit = pool.resources.memory;
  }

  return service;
}

function formatIndex(index: number): string {
  return String(index + 1).padStart(2, "0");
}
